// Counts include checked entries: filtering them out could match the wrong log.
const brakHistoryMatchColumns = '''
  (SELECT COUNT(*) FROM MICQLOG L
   WHERE L.MAGAZINE_ID = -7 AND L.MAGAZINESTATUS_ID = mwz.MAGAZINEID
     AND L.PRIM = mc.ART_MATERIAL AND L.USERICQ = mwz.KOLVO) AS LOG_COUNT,
  (SELECT COUNT(*) FROM MICQLOG L
   WHERE L.MAGAZINE_ID = -7 AND L.MAGAZINESTATUS_ID = mwz.MAGAZINEID
     AND L.PRIM = mc.ART_MATERIAL AND L.USERICQ = mwz.KOLVO
     AND L.CHECKED IS NULL) AS UNCHECKED_COUNT,
  (SELECT COUNT(*) FROM MAGAZINEWOTDELKAZAM B
   JOIN MCUSTOM C ON C.ID = B.MCUSTOMID
   JOIN MAGAZINEZAM Z ON Z.ID = B.MAGAZINEZAMID
   WHERE Z.PRIM = 'Брак стекла' AND B.MAGAZINEID = mwz.MAGAZINEID
     AND C.ART_MATERIAL = mc.ART_MATERIAL AND B.KOLVO = mwz.KOLVO) AS BRAK_COUNT
''';

String? brakDeletionBlockedReason(Map<dynamic, dynamic> row) {
  if (row['LOG_COUNT'] == 0) return 'Удаление этой записи недоступно';
  if (row['LOG_COUNT'] != 1 || row['BRAK_COUNT'] != 1) {
    return 'Удаление этой записи недоступно';
  }
  if (row['UNCHECKED_COUNT'] != 1) return 'Запись уже обработана — удаление недоступно';
  return null;
}

// All mutations precede the single final SUSPEND, so a statement error rolls
// back all changes. Lock the source, log, parent and detail notes first.
const deleteBrakSql = '''
EXECUTE BLOCK (TARGET_ID INTEGER = ?)
RETURNS (DELETED_COUNT INTEGER)
AS
DECLARE VARIABLE SOURCE_ID TYPE OF COLUMN MAGAZINEWOTDELKAZAM.ID;
DECLARE VARIABLE ORDER_ID TYPE OF COLUMN MAGAZINEWOTDELKAZAM.MAGAZINEID;
DECLARE VARIABLE ARTICLE TYPE OF COLUMN MCUSTOM.ART_MATERIAL;
DECLARE VARIABLE QUANTITY TYPE OF COLUMN MAGAZINEWOTDELKAZAM.KOLVO;
DECLARE VARIABLE LOG_ID TYPE OF COLUMN MICQLOG.ID;
DECLARE VARIABLE LOCKED_LOG_ID TYPE OF COLUMN MICQLOG.ID;
DECLARE VARIABLE MATCHES INTEGER;
DECLARE VARIABLE BRAK_MATCHES INTEGER;
DECLARE VARIABLE PARENT_ID TYPE OF COLUMN MAGAZINEZAM.ID;
DECLARE VARIABLE LOCKED_PARENT_ID TYPE OF COLUMN MAGAZINEZAM.ID;
DECLARE VARIABLE NOTE_DATE TYPE OF COLUMN MAGAZINEZAM.DATEINSERT;
DECLARE VARIABLE COMMENT_TEXT TYPE OF COLUMN MAGAZINEWOTDELKAZAM.PRIM;
DECLARE VARIABLE FRAGMENT BLOB SUB_TYPE TEXT;
DECLARE VARIABLE DETAIL_ID TYPE OF COLUMN MCUSTOM.ID;
DECLARE VARIABLE NOTE_TEXT TYPE OF COLUMN MCUSTOM.PRIM;
DECLARE VARIABLE NOTE_POSITION INTEGER;
DECLARE VARIABLE REMOVE_FROM INTEGER;
DECLARE VARIABLE REMOVE_LENGTH INTEGER;
DECLARE VARIABLE NOTES_SAFE INTEGER;
BEGIN
  DELETED_COUNT = 0;
  SOURCE_ID = NULL;
  LOCKED_LOG_ID = NULL;
  SELECT B.ID FROM MAGAZINEWOTDELKAZAM B
    WHERE B.ID = :TARGET_ID WITH LOCK INTO :SOURCE_ID;
  IF (SOURCE_ID IS NOT NULL) THEN
  BEGIN
    SELECT B.MAGAZINEID, C.ART_MATERIAL, B.KOLVO,
           B.MAGAZINEZAMID, B.PRIM, Z.DATEINSERT
      FROM MAGAZINEWOTDELKAZAM B
      JOIN MCUSTOM C ON C.ID = B.MCUSTOMID
      JOIN MAGAZINEZAM Z ON Z.ID = B.MAGAZINEZAMID
      WHERE B.ID = :SOURCE_ID AND Z.PRIM = 'Брак стекла'
      INTO :ORDER_ID, :ARTICLE, :QUANTITY,
           :PARENT_ID, :COMMENT_TEXT, :NOTE_DATE;
    SELECT COUNT(*), MIN(L.ID) FROM MICQLOG L
      WHERE L.MAGAZINE_ID = -7 AND L.MAGAZINESTATUS_ID = :ORDER_ID
        AND L.PRIM = :ARTICLE AND L.USERICQ = :QUANTITY
      INTO :MATCHES, :LOG_ID;
    SELECT COUNT(*) FROM MAGAZINEWOTDELKAZAM B
      JOIN MCUSTOM C ON C.ID = B.MCUSTOMID
      JOIN MAGAZINEZAM Z ON Z.ID = B.MAGAZINEZAMID
      WHERE Z.PRIM = 'Брак стекла' AND B.MAGAZINEID = :ORDER_ID
        AND C.ART_MATERIAL = :ARTICLE AND B.KOLVO = :QUANTITY
      INTO :BRAK_MATCHES;
    IF (MATCHES = 1 AND BRAK_MATCHES = 1) THEN
    BEGIN
      SELECT L.ID FROM MICQLOG L
        WHERE L.ID = :LOG_ID AND L.CHECKED IS NULL
          AND L.MAGAZINE_ID = -7 AND L.MAGAZINESTATUS_ID = :ORDER_ID
          AND L.PRIM = :ARTICLE AND L.USERICQ = :QUANTITY
        WITH LOCK INTO :LOCKED_LOG_ID;
      IF (LOCKED_LOG_ID IS NOT NULL) THEN
      BEGIN
        SELECT Z.ID FROM MAGAZINEZAM Z WHERE Z.ID = :PARENT_ID
          WITH LOCK INTO :LOCKED_PARENT_ID;
        FRAGMENT = TRIM(COALESCE(COMMENT_TEXT, '')) || ' (' ||
          LPAD(CAST(EXTRACT(DAY FROM NOTE_DATE) AS VARCHAR(2)), 2, '0') || '.' ||
          LPAD(CAST(EXTRACT(MONTH FROM NOTE_DATE) AS VARCHAR(2)), 2, '0') || ')';
        NOTES_SAFE = 1;
        IF (NOTE_DATE IS NULL) THEN NOTES_SAFE = 0;
        /* Creation appends the note to ALL matching MCUSTOM rows.
           Lock and validate all of them before making any changes. */
        FOR SELECT C.ID, C.PRIM FROM MCUSTOM C
          WHERE C.CUSTOMID = :ORDER_ID AND C.ART_MATERIAL = :ARTICLE
          ORDER BY C.ID WITH LOCK INTO :DETAIL_ID, :NOTE_TEXT
        DO
        BEGIN
          NOTE_POSITION = POSITION(FRAGMENT IN COALESCE(NOTE_TEXT, ''));
          IF (NOTE_POSITION > 0) THEN
          BEGIN
            IF (POSITION(FRAGMENT IN SUBSTRING(NOTE_TEXT FROM
                NOTE_POSITION + CHAR_LENGTH(FRAGMENT))) > 0) THEN NOTES_SAFE = 0;
            IF (NOTE_POSITION > 1 AND
                SUBSTRING(NOTE_TEXT FROM NOTE_POSITION - 1 FOR 1) <> ' ') THEN NOTES_SAFE = 0;
            IF (NOTE_POSITION + CHAR_LENGTH(FRAGMENT) <= CHAR_LENGTH(NOTE_TEXT) AND
                SUBSTRING(NOTE_TEXT FROM NOTE_POSITION + CHAR_LENGTH(FRAGMENT) FOR 1) <> ' ') THEN NOTES_SAFE = 0;
          END
        END
        IF (NOTES_SAFE = 1) THEN
        BEGIN
          FOR SELECT C.ID, C.PRIM FROM MCUSTOM C
            WHERE C.CUSTOMID = :ORDER_ID AND C.ART_MATERIAL = :ARTICLE
            INTO :DETAIL_ID, :NOTE_TEXT
          DO
          BEGIN
            NOTE_POSITION = POSITION(FRAGMENT IN COALESCE(NOTE_TEXT, ''));
            IF (NOTE_POSITION > 0) THEN
            BEGIN
              REMOVE_FROM = NOTE_POSITION;
              REMOVE_LENGTH = CHAR_LENGTH(FRAGMENT);
              IF (NOTE_POSITION > 1) THEN
              BEGIN
                REMOVE_FROM = REMOVE_FROM - 1;
                REMOVE_LENGTH = REMOVE_LENGTH + 1;
              END
              ELSE IF (CHAR_LENGTH(NOTE_TEXT) > REMOVE_LENGTH) THEN
                REMOVE_LENGTH = REMOVE_LENGTH + 1;
              UPDATE MCUSTOM SET PRIM =
                SUBSTRING(:NOTE_TEXT FROM 1 FOR :REMOVE_FROM - 1) ||
                SUBSTRING(:NOTE_TEXT FROM :REMOVE_FROM + :REMOVE_LENGTH)
                WHERE ID = :DETAIL_ID;
            END
          END
          DELETE FROM MAGAZINEWOTDELKAZAM WHERE ID = :SOURCE_ID;
          DELETE FROM MICQLOG WHERE ID = :LOCKED_LOG_ID AND CHECKED IS NULL;
          DELETE FROM MAGAZINEZAM WHERE ID = :PARENT_ID
            AND NOT EXISTS (SELECT 1 FROM MAGAZINEWOTDELKAZAM B
                            WHERE B.MAGAZINEZAMID = :PARENT_ID);
          DELETED_COUNT = 1;
        END
      END
    END
  END
  SUSPEND;
END
''';
